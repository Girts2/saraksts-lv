export function buildWesternPsychologyProfile(birthChart) {
    const { planets, houses, aspects } = birthChart;

    // 1. Atrodam kritiskos aspektus
    // Aspektu formāts tiks izveidots western.js vēlāk, taču te filtrējam jau esošos.
    const activeConflicts = aspects.filter(a => 
        (a.type === 'Square' || a.type === 'Opposition') && 
        CRITICAL_ASPECTS[`${a.p1}_${a.type}_${a.p2}`]
    );

    const getSafe = (obj, key) => obj[key] || `(Nepieciešama analīze ${key})`;

    const nnDesc = getSafe(WESTERN_NODES, `SN_${planets.Ketu.sign}_NN_${planets.Rahu.sign}`);
    
    return {
        identity: getSafe(WESTERN_EGO_STRUCTURE, planets.Saule.sign),
        socialMask: getSafe(WESTERN_EGO_STRUCTURE, planets.Ascendant.sign), // Izmanto Ego sturktūru ka Ascendentam
        emotionalNeeds: `${getSafe(WESTERN_MOON_NEEDS, planets.Meness.sign)} Mēness ${planets.Meness.house}. mājā — šīs vajadzības visasāk izpaužas tieši šīs dzīves sfēras kontekstā.`,
        thinkingStyle: getSafe(WESTERN_COMMUNICATION, planets.Merkurs.sign),
        communication: getSafe(WESTERN_COMMUNICATION, planets.Merkurs.sign), 
        loveLanguage: getSafe(WESTERN_VENUS, planets.Venera.sign),
        values: `Vērtību sistēmu nosaka Venēras izpausme: ${getSafe(WESTERN_VENUS, planets.Venera.sign).split('.')[0]}.`,
        motivation: getSafe(WESTERN_MARS, planets.Marss.sign),
        aggression: `${getSafe(WESTERN_MARS, planets.Marss.sign)} Destruktīvais potenciāls visspēcīgāk var izpausties ${HOUSES[planets.Marss.house]?.sector_loc || 'nezināmā jomā'}.`,
        innerConflicts: activeConflicts.length > 0
            ? activeConflicts.map(c => CRITICAL_ASPECTS[`${c.p1}_${c.type}_${c.p2}`].profile).join(" ")
            : null,
        criticalAspectsBlocks: activeConflicts.map(c => CRITICAL_ASPECTS[`${c.p1}_${c.type}_${c.p2}`]),
        boundaries: getSafe(WESTERN_SATURN, planets.Saturns.sign),
        philosophy: getSafe(WESTERN_JUPITER_PHILOSOPHY, planets.Jupiters.sign),
        blackmailPoints: planets.Lilita
            ? getSafe(WESTERN_LILITH, planets.Lilita.sign)
            : null,
        trauma: planets.Hirons
            ? getSafe(WESTERN_CHIRON, planets.Hirons.house + '. māja')
            : null,
        illusions: getSafe(WESTERN_NEPTUNE, planets.Neptuns.sign),
        reactionToChange: getSafe(WESTERN_URANUS, planets.Urans.sign),
        growthVector: nnDesc
    };
}
