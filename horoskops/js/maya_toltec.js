export function getBaseData(dateObj) {
    // dateObj = JS Date objekts
    const anchor = new Date("1979-11-09T00:00:00Z");
    
    // JS dates subtraction gives milliseconds
    const diffMs = dateObj.getTime() - anchor.getTime();
    const diffDays = Math.floor(diffMs / 86400000);
    
    // Tones formula Python: ((11 - 1 + diff) % 13) + 1
    let toneMod = (10 + diffDays) % 13;
    if (toneMod < 0) toneMod += 13;
    const tone = toneMod + 1;
    
    let signIdx = (3 + diffDays) % 20;
    if (signIdx < 0) signIdx += 20;
    const sign = SIGNS[signIdx];
    
    const gateAnchor = new Date("2025-11-03T00:00:00Z");
    const diffGate = Math.floor((dateObj.getTime() - gateAnchor.getTime()) / 86400000);
    let gateMod = diffGate % 73;
    if (gateMod < 0) gateMod += 73;
    const gateNum = gateMod + 1;
    
    const colorVal = COLORS[signIdx % 4];

    let nakIdx = (17 + diffDays) % 27;
    if (nakIdx < 0) nakIdx += 27;

    // Kin (1-260 Tzolkin dienas skaitlis) — atgūts no tone+signIdx ar Ķīniešu atlikumu
    // teorēmu (CRT), jo abi jau ir korekti aprēķināti no tā paša diffDays: kin0 ≡ signIdx
    // (mod 20) un kin0 ≡ tone-1 (mod 13). 20⁻¹ mod 13 = 2 (jo 20·2=40≡1 mod13).
    const kMod13 = (((2 * (tone - 1 - signIdx)) % 13) + 13) % 13;
    const kin = signIdx + 20 * kMod13 + 1;

    return {
        date: dateObj,
        tone: tone,
        sign: sign,
        sign_idx: signIdx,
        kin: kin,
        color: colorVal,
        tatva: TATVAS_MAP[sign] || "Nezināms",
        gate: gateNum,
        demon_info: DEMONS_72[gateNum] || ["Nezināms", "Trūkst datu"],
        nakshatra: NAKSHATRAS[nakIdx]
    };
}

export function getLifeCycle(birthDate, currentDate) {
    const ageDays = (currentDate.getTime() - birthDate.getTime()) / 86400000;
    // Aizsargā pret negatīvu vecumu (dzimšana nākotnē vai pēc references datuma) — citādi
    // cikls kļūst negatīvs un WAVE_DESCRIPTIONS[idx] ir undefined → avārija (".Krasa").
    const ageYears = Math.max(0, ageDays / 365.25);

    let cycleYear = Math.floor(ageYears % 52) + 1;
    let waveIndex = Math.floor((cycleYear - 1) / 13);
    let yearInWave = ((cycleYear - 1) % 13) + 1;
    
    let waveIndexSafe = waveIndex % 4;
    
    return {
        age: Number(ageYears.toFixed(1)),
        cycle_year: cycleYear,
        wave: WAVE_DESCRIPTIONS[waveIndexSafe],
        year_in_wave: yearInWave
    };
}

export function getDailyImpact(birthData, currentData) {
    let diff = currentData.sign_idx - birthData.sign_idx;
    if (diff < 0) diff += 20;
    let impactMod = (diff % 13);
    return impactMod + 1;
}

