// 13 Moon Calendar
export function calculate13MoonDate(dateObj) {
    const year = dateObj.getFullYear();
    const month = dateObj.getMonth();
    const day = dateObj.getDate();
    
    let startYear = (month < 6 || (month === 6 && day < 26)) ? year - 1 : year;
    let startOf13Moon = new Date(Date.UTC(startYear, 6, 26)); // Use UTC to avoid timezone shifts
    let target = new Date(Date.UTC(year, month, day));
    
    let diffMs = target.getTime() - startOf13Moon.getTime();
    let diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
    
    let nextYearIsLeap = ((startYear + 1) % 4 === 0 && (startYear + 1) % 100 !== 0) || ((startYear + 1) % 400 === 0);
    if (nextYearIsLeap && (month > 1 || (month === 1 && day === 29))) {
        diffDays -= 1; 
    }
    
    if (month === 1 && day === 29) {
        return { moon: 0, day: 0, moonName: "Hunab Ku 0.0", desc: "Ārpus laika papildu diena (Gara sinhronizācija)." };
    }
    
    if (month === 6 && day === 25) {
        return { moon: 0, day: 0, moonName: "Ārpus Laika Diena (Day Out of Time)", desc: "Pārejas diena pirms Jaunā gada. Brīvība un māksla." };
    }
    
    const moonNames = [
        "Magnētiskais (1)", "Lunārais (2)", "Elektriskais (3)", "Pašesošais (4)", "Virstoņu (5)",
        "Ritmiskais (6)", "Rezonējošais (7)", "Galaktiskais (8)", "Saules (9)", "Planetārais (10)",
        "Spektrālais (11)", "Kristāliskais (12)", "Kosmiskais (13)"
    ];
    
    let currentMoonIndex = Math.floor(diffDays / 28);
    let currentMoonDay = (diffDays % 28) + 1;
    
    if(currentMoonIndex >= 13) currentMoonIndex = 12; // safety
    
    return {
        moon: currentMoonIndex + 1,
        day: currentMoonDay,
        moonName: moonNames[currentMoonIndex] + " Mēness",
        desc: `13 Mēnešu Kalendārs: ${moonNames[currentMoonIndex]} Mēness, ${currentMoonDay}. diena.`
    };
}

export function calculateChronoPsi(moonNumber, moonDay) {
    if (moonNumber === 0) return { kin: null, info: "N/A (Ārpus laika)" };
    let dayOfYear = ((moonNumber - 1) * 28) + moonDay;
    let chronoPsiKin = dayOfYear % 260;
    if (chronoPsiKin === 0) chronoPsiKin = 260;
    
    let tone = (chronoPsiKin % 13) || 13;
    let sealIndex = (chronoPsiKin - 1) % 20;
    
    return { kin: chronoPsiKin, tone: tone, sealIndex: sealIndex, sealName: SIGNS[sealIndex], info: "Planētas atmiņas reģistrs, kas fiksē kolektīvo evolūciju." };
}


